// Уроки шахмат для начинающих: короткое объяснение + задание на доске.
//
// Типы шагов:
//  info    — просто прочитать (доска для иллюстрации);
//  squares — нажать на названные поля по очереди (знакомство с координатами);
//  stars   — пройти фигурой по всем звёздам (ходят только белые);
//  capture — съесть все чёрные фигуры (чёрные не отвечают);
//  move    — найти верный ход в позиции (проверка функцией accept);
//  play    — довести позицию до мата против компьютера.

export interface MoveCheck {
  san: string;
  uci: string;
  /** Ход поставил шах / мат / пат. */
  check: boolean;
  mate: boolean;
  stalemate: boolean;
  /** Ходившая фигура: 1 пешка … 6 король. */
  piece: number;
  /** Взятая фигура (0 — без взятия). */
  captured: number;
  castle: boolean;
  enPassant: boolean;
}

interface Base {
  /** Что объясняем / что сделать. Пустая строка — разрыв абзаца. */
  text: string[];
  fen: string;
  /** Подсветить поля (для объяснений). */
  marks?: string[];
}

export type LessonStep =
  | (Base & { kind: "info" })
  | (Base & { kind: "squares"; squares: string[] })
  | (Base & { kind: "stars"; stars: string[]; par?: number })
  | (Base & { kind: "capture"; par?: number })
  | (Base & {
      kind: "move";
      accept: (c: MoveCheck) => boolean;
      /** Подсказка о том, почему ход не подходит (если есть). */
      why?: (c: MoveCheck) => string | null;
      solution: string;
      success?: string;
    })
  | (Base & { kind: "play"; maxMoves: number });

export interface Lesson {
  id: string;
  icon: string;
  title: string;
  desc: string;
  steps: LessonStep[];
}

